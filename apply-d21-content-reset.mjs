#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check');
const root = process.cwd();

const eventsDir = path.join(root, 'src', 'game', 'content', 'events');
const legacyRoot = path.join(root, 'docs', 'content', 'events', 'legacy');
const archiveDir = path.join(legacyRoot, 'runtime-reset-archive');
const manifestPath = path.join(legacyRoot, 'RUNTIME_RESET_MANIFEST.md');
const eventsReadmePath = path.join(eventsDir, 'README_D21.md');
const v2ReadmePath = path.join(eventsDir, 'v2', 'README.md');

function fail(message) {
  throw new Error(`[D2.1] ${message}`);
}

function ensureFileExists(filePath, label) {
  if (!fs.existsSync(filePath)) fail(`${label} not found: ${path.relative(root, filePath)}`);
}

function walk(dir) {
  const entries = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      entries.push(...walk(fullPath));
      continue;
    }
    entries.push(fullPath);
  }
  return entries;
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    fail(`Invalid JSON in ${path.relative(root, filePath)}: ${error.message}`);
  }
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/');
}

function eventDisposition(relativePath, event) {
  const id = String(event.id ?? '');
  const kind = String(event.kind ?? '');

  if (kind === 'critical') {
    return { type: 'keep', bucket: 'system/critical', reason: 'critical system event' };
  }

  if (id.startsWith('origin_')) {
    return { type: 'keep', bucket: 'origins', reason: 'origin event' };
  }

  return { type: 'archive', bucket: 'legacy', reason: 'legacy narrative/event content reset' };
}

function listEventFiles() {
  if (!fs.existsSync(eventsDir)) return [];
  return walk(eventsDir)
    .filter((filePath) => filePath.endsWith('.json'))
    .filter((filePath) => !toPosix(path.relative(eventsDir, filePath)).startsWith('v2/'));
}

function buildPlan() {
  const eventFiles = listEventFiles();
  const keep = [];
  const archive = [];

  for (const filePath of eventFiles) {
    const relativePath = path.relative(eventsDir, filePath);
    const event = readJson(filePath);
    const disposition = eventDisposition(relativePath, event);
    const item = {
      absolutePath: filePath,
      relativePath,
      eventId: String(event.id ?? path.basename(filePath, '.json')),
      kind: String(event.kind ?? 'unknown'),
      disposition,
    };
    if (disposition.type === 'keep') keep.push(item);
    else archive.push(item);
  }

  keep.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
  archive.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
  return { keep, archive };
}

function mkdirp(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
}

function writeFile(filePath, content) {
  mkdirp(path.dirname(filePath));
  fs.writeFileSync(filePath, content, 'utf8');
}

function removeIfExists(targetPath) {
  if (!fs.existsSync(targetPath)) return;
  fs.rmSync(targetPath, { recursive: true, force: true });
}

function copyFile(src, dest) {
  mkdirp(path.dirname(dest));
  fs.copyFileSync(src, dest);
}

function writeManifest(plan) {
  const lines = [];
  lines.push('# D2.1 Runtime Content Reset Manifest', '');
  lines.push('This manifest was generated by `apply-d21-content-reset.mjs`.', '');
  lines.push('## Purpose', '');
  lines.push('- remove legacy narrative runtime content from `src/game/content/events`;');
  lines.push('- preserve only Origins and Critical system events in the active runtime path;');
  lines.push('- archive all other JSON Event definitions under `docs/content/events/legacy/runtime-reset-archive/`;');
  lines.push('- prepare an empty `src/game/content/events/v2/` directory for new V2 content.', '');
  lines.push(`Kept files: **${plan.keep.length}**`);
  lines.push(`Archived files: **${plan.archive.length}**`, '');

  lines.push('## Kept in runtime', '');
  if (plan.keep.length === 0) lines.push('_None found._', '');
  else {
    for (const item of plan.keep) {
      lines.push(`- \`${toPosix(item.relativePath)}\` → \`${item.disposition.bucket}\` (${item.eventId}, ${item.kind})`);
    }
    lines.push('');
  }

  lines.push('## Archived out of runtime', '');
  if (plan.archive.length === 0) lines.push('_No archive candidates found._', '');
  else {
    for (const item of plan.archive) {
      lines.push(`- \`${toPosix(item.relativePath)}\` (${item.eventId}, ${item.kind})`);
    }
    lines.push('');
  }

  writeFile(manifestPath, lines.join('\n'));
}

function writeReadmes() {
  const readme = [
    '# Runtime Events — D2.1 Reset',
    '',
    'This directory now contains only **active runtime JSON Events** that remain part of the temporary V2 runtime surface during the D2 refactor.',
    '',
    'Allowed here after D2.1:',
    '',
    '- `origins/`',
    '- `system/critical/`',
    '- `v2/` (new V2 authored content)',
    '',
    'Legacy narrative catalogs were archived to:',
    '',
    '- `docs/content/events/legacy/runtime-reset-archive/`',
    '',
    'Do not reintroduce legacy narrative Events directly into this runtime path. New authored content belongs under `src/game/content/events/v2/`.',
    '',
  ].join('\n');
  writeFile(eventsReadmePath, readme);

  const v2Readme = [
    '# V2 Runtime Event Slot',
    '',
    'New post-reset runtime content belongs in this directory.',
    '',
    'Suggested substructure:',
    '',
    '- `childhood/`',
    '- `major-tracks/`',
    '- `mini-arcs/`',
    '- `generic/`',
    '',
    'D2.1 creates this directory empty on purpose.',
    '',
  ].join('\n');
  writeFile(v2ReadmePath, v2Readme);
}

function apply(plan) {
  mkdirp(legacyRoot);
  removeIfExists(archiveDir);
  mkdirp(archiveDir);

  const stagedKeep = [];
  for (const item of plan.keep) {
    const targetRelative = item.disposition.bucket === 'origins'
      ? path.join('origins', path.basename(item.relativePath))
      : path.join('system', 'critical', path.basename(item.relativePath));
    stagedKeep.push({ ...item, targetRelative });
  }

  for (const item of plan.archive) {
    const archivePath = path.join(archiveDir, item.relativePath);
    copyFile(item.absolutePath, archivePath);
  }

  const keepCopies = stagedKeep.map((item) => ({
    targetRelative: item.targetRelative,
    content: fs.readFileSync(item.absolutePath, 'utf8'),
  }));

  removeIfExists(eventsDir);
  mkdirp(eventsDir);
  mkdirp(path.join(eventsDir, 'origins'));
  mkdirp(path.join(eventsDir, 'system', 'critical'));
  mkdirp(path.join(eventsDir, 'v2'));

  for (const item of keepCopies) {
    writeFile(path.join(eventsDir, item.targetRelative), item.content);
  }

  writeReadmes();
  writeManifest(plan);
}

function printPlan(plan) {
  console.log('D2.1 Runtime Content Reset');
  console.log(`- keep in runtime: ${plan.keep.length}`);
  console.log(`- archive out of runtime: ${plan.archive.length}`);
  console.log('');
  if (plan.keep.length > 0) {
    console.log('Kept:');
    for (const item of plan.keep) {
      console.log(`  KEEP    ${toPosix(item.relativePath)}  [${item.eventId}] -> ${item.disposition.bucket}`);
    }
    console.log('');
  }
  if (plan.archive.length > 0) {
    console.log('Archive candidates:');
    for (const item of plan.archive.slice(0, 40)) {
      console.log(`  ARCHIVE ${toPosix(item.relativePath)}  [${item.eventId}]`);
    }
    if (plan.archive.length > 40) console.log(`  ... ${plan.archive.length - 40} more`);
    console.log('');
  }
}

ensureFileExists(path.join(root, 'package.json'), 'package.json');
ensureFileExists(eventsDir, 'src/game/content/events');

const plan = buildPlan();
printPlan(plan);

if (checkOnly) {
  console.log('[D2.1] Check only — no file written.');
  process.exit(0);
}

apply(plan);
console.log('[D2.1] Applied successfully.');
